create extension if not exists vector;
create extension if not exists pgcrypto;

create table if not exists public.users (
  id uuid primary key default gen_random_uuid(),
  display_name text not null check (char_length(display_name) between 2 and 100),
  email text not null unique check (char_length(email) <= 254),
  password_hash text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.documents (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.users(id) on delete cascade,
  filename text not null,
  page_count integer not null default 1 check (page_count >= 1),
  page_count_known boolean not null default false,
  storage_path text,
  created_at timestamptz not null default now()
);

create table if not exists public.document_chunks (
  id bigint generated by default as identity primary key,
  document_id uuid not null references public.documents(id) on delete cascade,
  chunk_index integer not null check (chunk_index >= 0),
  page_number integer not null default 1 check (page_number >= 1),
  content text not null,
  embedding vector(768) not null,
  unique (document_id, chunk_index)
);

create table if not exists public.chat_threads (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.users(id) on delete cascade,
  title text not null default 'New chat',
  description text not null default 'Start a conversation',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.chat_documents (
  chat_id uuid not null references public.chat_threads(id) on delete cascade,
  document_id uuid not null references public.documents(id) on delete cascade,
  primary key (chat_id, document_id)
);

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  chat_id uuid not null references public.chat_threads(id) on delete cascade,
  role text not null check (role in ('user', 'assistant')),
  content text not null,
  sources jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists documents_user_id_idx on public.documents(user_id);
create index if not exists chat_threads_user_updated_idx on public.chat_threads(user_id, updated_at desc);
create index if not exists chat_documents_document_id_idx on public.chat_documents(document_id);
