  select 1;
$$;

grant execute on function public.initialize_mydocx_schema() to service_role;

drop function if exists public.list_mydocx_documents(uuid);
create function public.list_mydocx_documents(p_user_id uuid)
returns table(
  id uuid,
  filename text,
  page_count integer,
  page_count_known boolean,
  has_file boolean,
  chunks bigint
)
language sql
stable
security definer
set search_path = public
as $$
  select d.id, d.filename, d.page_count, d.page_count_known,
         d.storage_path is not null, count(c.id)::bigint
  from documents d
  left join document_chunks c on c.document_id = d.id
  where d.user_id = p_user_id
  group by d.id
  order by d.created_at desc;
$$;

grant execute on function public.list_mydocx_documents(uuid) to service_role;

create or replace function public.count_mydocx_chunks(
  p_user_id uuid,
  p_document_ids uuid[] default null,
  p_page_numbers integer[] default null
)
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select count(c.id)
  from document_chunks c
  join documents d on d.id = c.document_id
  where d.user_id = p_user_id
    and (p_document_ids is null or d.id = any(p_document_ids))
    and (p_page_numbers is null or c.page_number = any(p_page_numbers));
$$;

grant execute on function public.count_mydocx_chunks(uuid, uuid[], integer[]) to service_role;

create or replace function public.get_mydocx_chunks(
  p_user_id uuid,
  p_document_ids uuid[] default null,
  p_page_numbers integer[] default null
)
returns table(document_id uuid, filename text, chunk_index integer, page_number integer, content text)
language sql
stable
security definer
set search_path = public
as $$
  select d.id, d.filename, c.chunk_index, c.page_number, c.content
  from document_chunks c
  join documents d on d.id = c.document_id
  where d.user_id = p_user_id
    and (p_document_ids is null or d.id = any(p_document_ids))
    and (p_page_numbers is null or c.page_number = any(p_page_numbers))
  order by d.id, c.chunk_index;
$$;

grant execute on function public.get_mydocx_chunks(uuid, uuid[], integer[]) to service_role;

create or replace function public.search_mydocx_chunks(
  p_user_id uuid,
  p_document_ids uuid[],
  p_page_numbers integer[],
  p_embedding vector(768),
  p_match_count integer
)
returns table(document_id uuid, filename text, chunk_index integer, page_number integer, content text, distance real)
language sql
stable
security definer
set search_path = public
as $$
  select d.id,
         d.filename,
         c.chunk_index,
         c.page_number,
         c.content,
         (c.embedding <=> p_embedding)::real as distance
  from document_chunks c
  join documents d on d.id = c.document_id
  where d.user_id = p_user_id
    and (p_document_ids is null or d.id = any(p_document_ids))
    and (p_page_numbers is null or c.page_number = any(p_page_numbers))
  order by c.embedding <=> p_embedding
  limit greatest(p_match_count, 1);
$$;

grant execute on function public.search_mydocx_chunks(uuid, uuid[], integer[], vector(768), integer) to service_role;

